    fun findOverflightLocation(latDeg: Double, lonDeg: Double): String {
        val lat = latDeg.toFloat()
        val lon = lonDeg.toFloat()
        var closestCountry: CountryEntry? = null
        var closestDistSq = Float.MAX_VALUE
        for (c in countries) {
            if (lat in c.minLat..c.maxLat && lon in c.minLon..c.maxLon) {
                val dLat = lat - c.lat
                val dLon = lon - c.lon
                val distSq = dLat * dLat + dLon * dLon
                if (distSq < closestDistSq) {
                    closestDistSq = distSq
                    closestCountry = c
                }
            }
        }
        if (closestCountry != null) {
            return closestCountry.nameDe
        }

        return when {
            lat > 66.5f -> "Arktischer Ozean"
            lat < -60.0f -> "Südlicher Ozean"
            lat in 30.0f..46.0f && lon in -5.0f..36.0f -> "Mittelmeer"
            lat in 10.0f..30.0f && lon in -90.0f..-60.0f -> "Karibisches Meer"
            lon in -70.0f..20.0f -> "Atlantischer Ozean"
            lon in 20.0f..142.0f && lat < 30.0f -> "Indischer Ozean"
            else -> "Pazifischer Ozean"
        }
    }
